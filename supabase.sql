create table if not exists public.menu_items (
  id         bigint generated by default as identity primary key,
  category   text not null,               -- カテゴリ名(炭火焼き など)
  name       text not null,               -- 品名(手羽先唐揚げ 500g のようにサイズ込み)
  price      int not null,                -- 価格(円)
  sort_no    int not null default 999,    -- 表示順
  available  boolean not null default true, -- false=売り切れ(フォームから隠す)
  created_at timestamptz not null default now()
