-- 注文テーブル
create table if not exists public.takeout_orders (
  id            bigint generated by default as identity primary key,
  created_at    timestamptz not null default now(),
  line_user_id  text not null default '',      -- 注文した客のLINEユーザーID
  customer_name text not null,                 -- お名前
  phone         text,                          -- 電話番号
  pickup_at     timestamptz not null,          -- 受取希望時刻
  items         jsonb not null,                -- [{name, price, qty}, ...]
  total         int not null,                  -- 合計金額(円)
  note          text,                          -- ご要望(任意)
  status        text not null default 'new'    -- new:新規 / done:受渡済み
);

alter table public.takeout_orders enable row level security;

-- 客(LIFFアプリ)からの書き込みを許可
create policy "anon insert" on public.takeout_orders
  for insert to anon with check (true);

-- 読み取りを許可(次工程の受注ボード用)
-- ※URLを知る人なら誰でも注文一覧を見られる簡易運用(v1)
create policy "anon select" on public.takeout_orders
  for select to anon using (true);

-- 受注ボード(次工程)でのリアルタイム配信を有効化
-- ※エラーが出る場合は実行しなくても注文フォーム自体には影響なし
alter publication supabase_realtime add table public.takeout_orders;

