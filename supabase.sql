-- ============================================
-- v1.4 定休日・臨時休業(ボードから設定する型)
-- ============================================

create table if not exists public.shop_holidays (
  id           bigint generated by default as identity primary key,
  kind         text not null check (kind in ('weekly', 'date')),
  day_of_week  int,     -- kind='weekly' の場合: 0=日 1=月 ... 6=土
  holiday_date date,    -- kind='date' の場合: その日を休業に
  created_at   timestamptz not null default now()
);
alter table public.shop_holidays enable row level security;

-- フォーム側は読み取りだけ許可(追加/削除はエッジファンクション経由)
create policy "anon select holidays" on public.shop_holidays
  for select to anon using (true);

-- 二重登録防止のユニーク制約
create unique index if not exists shop_holidays_weekly_uniq
  on public.shop_holidays (day_of_week) where kind = 'weekly';
create unique index if not exists shop_holidays_date_uniq
  on public.shop_holidays (holiday_date) where kind = 'date';
